#!/usr/bin/env node
/**
 * Ships only the Bootstrap Icons the site uses (about 30 of 2,000): a smaller stylesheet and a font of a few kB.
 * Reads every `bi-<name>` found in src/ and in the course.json files, and writes
 *   src/icons.css  and  src/fonts/optimal-icons.woff2
 *   node scripts/generate-icons.mjs          write the files
 *   node scripts/generate-icons.mjs --check  fail if they are out of date (an icon was added or removed)
 * To use a new icon in a template or in course.json, add it there and run `npm run icons`.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'node_modules', 'bootstrap-icons', 'font');

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (/\.(html|ts|css|scss)$/.test(name) && !name.endsWith('.spec.ts') && name !== 'icons.css') out.push(path);
  }
  return out;
}

/** Icon names (`bi-x`) used in the given texts that exist in the Bootstrap Icons set. */
export function usedIcons(texts, known) {
  const found = new Set();
  for (const text of texts) for (const m of text.matchAll(/\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) if (m[1] in known) found.add(m[1]);
  return [...found].sort();
}

export async function build() {
  const known = JSON.parse(readFileSync(join(iconsDir, 'bootstrap-icons.json'), 'utf8')); // name -> code point
  const sources = walk(join(root, 'src')).map(p => readFileSync(p, 'utf8'));
  const coursesDir = join(root, 'public', 'courses');
  for (const id of readdirSync(coursesDir)) {
    const meta = join(coursesDir, id, 'course.json');
    if (existsSync(meta)) sources.push(readFileSync(meta, 'utf8'));
  }
  const names = usedIcons(sources, known);
  const text = names.map(n => String.fromCodePoint(known[n])).join('');
  const font = await subsetFont(readFileSync(join(iconsDir, 'fonts', 'bootstrap-icons.woff2')), text, { targetFormat: 'woff2' });
  const css = [
    '/* Generated by scripts/generate-icons.mjs: do not edit. Run `npm run icons` after using a new bi-* icon. */',
    "@font-face { font-display: block; font-family: 'bootstrap-icons'; src: url('./fonts/optimal-icons.woff2') format('woff2'); }",
    '.bi::before, [class^="bi-"]::before, [class*=" bi-"]::before {',
    '  display: inline-block; font-family: bootstrap-icons !important; font-style: normal; font-weight: normal !important;',
    '  font-variant: normal; text-transform: none; line-height: 1; vertical-align: -0.125em; -webkit-font-smoothing: antialiased;',
    '}',
    ...names.map(n => `.bi-${n}::before { content: "\\${known[n].toString(16)}"; }`),
    '',
  ].join('\n');
  return { css, font, names };
}

async function main() {
  const { css, font, names } = await build();
  const cssPath = join(root, 'src', 'icons.css');
  const fontPath = join(root, 'src', 'fonts', 'optimal-icons.woff2');
  if (process.argv.includes('--check')) {
    const sameCss = existsSync(cssPath) && readFileSync(cssPath, 'utf8') === css;
    if (!sameCss) {
      console.error('src/icons.css is out of date (an icon was added or removed). Run: npm run icons');
      process.exit(1);
    }
    console.log(`icons are up to date (${names.length}).`);
    return;
  }
  mkdirSync(dirname(fontPath), { recursive: true });
  writeFileSync(cssPath, css);
  writeFileSync(fontPath, font);
  console.log(`icons written: ${names.length} icons, font ${font.length} bytes`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
